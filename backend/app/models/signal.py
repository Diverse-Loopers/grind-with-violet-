"""
Signal ORM model and Pydantic schemas.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field, ConfigDict
from sqlalchemy import Column, DateTime, Float, Integer, String, Text

from app.database import Base


class StrategyType(str, Enum):
    SPREAD = "SPREAD"
    GAP = "GAP"
    PAIRS = "PAIRS"


class SignalType(str, Enum):
    BUY = "BUY"
    SELL = "SELL"


class DataQuality(str, Enum):
    LIVE = "LIVE"
    DELAYED = "DELAYED"
    CACHED = "CACHED"
    DEMO = "DEMO"


class SignalStatus(str, Enum):
    PENDING = "PENDING"
    ACCEPTED = "ACCEPTED"
    REJECTED = "REJECTED"
    EXPIRED = "EXPIRED"


class Signal(Base):
    """Trading signal generated by a strategy."""

    __tablename__ = "signals"

    id: int = Column(Integer, primary_key=True, autoincrement=True)  # type: ignore[assignment]
    instrument_id: int = Column(Integer, nullable=False, index=True)  # type: ignore[assignment]
    trading_symbol: str = Column(String(50), nullable=False, index=True)  # type: ignore[assignment]
    strategy: str = Column(String(20), nullable=False, index=True)  # type: ignore[assignment]
    signal_type: str = Column(String(10), nullable=False)  # type: ignore[assignment]
    entry_price: float = Column(Float, nullable=False)  # type: ignore[assignment]
    reference_price: float = Column(Float, nullable=True)  # type: ignore[assignment]
    expected_edge_pct: float = Column(Float, nullable=True)  # type: ignore[assignment]
    estimated_cost_pct: float = Column(Float, nullable=True)  # type: ignore[assignment]
    net_edge_pct: float = Column(Float, nullable=True)  # type: ignore[assignment]
    confidence_score: float = Column(Float, nullable=True)  # type: ignore[assignment]
    reason: str = Column(Text, nullable=True)  # type: ignore[assignment]
    data_quality: str = Column(String(20), nullable=False, default=DataQuality.DEMO.value)  # type: ignore[assignment]
    quote_timestamp: datetime = Column(DateTime, nullable=True)  # type: ignore[assignment]
    bid_price: float = Column(Float, nullable=True)  # type: ignore[assignment]
    ask_price: float = Column(Float, nullable=True)  # type: ignore[assignment]
    spread_pct: float = Column(Float, nullable=True)  # type: ignore[assignment]
    volume: int = Column(Integer, nullable=True)  # type: ignore[assignment]
    relative_volume: float = Column(Float, nullable=True)  # type: ignore[assignment]
    volatility: float = Column(Float, nullable=True)  # type: ignore[assignment]
    status: str = Column(String(20), nullable=False, default=SignalStatus.PENDING.value, index=True)  # type: ignore[assignment]
    rejection_reason: str = Column(Text, nullable=True)  # type: ignore[assignment]
    created_at: datetime = Column(DateTime, nullable=False, default=lambda: datetime.now(timezone.utc))  # type: ignore[assignment]

    def __repr__(self) -> str:
        return f"<Signal {self.id} {self.strategy} {self.signal_type} {self.trading_symbol}>"


# ── Pydantic Schemas ──────────────────────────────────────────


class SignalCreate(BaseModel):
    """Schema for creating a signal."""

    instrument_id: int
    trading_symbol: str
    strategy: StrategyType
    signal_type: SignalType
    entry_price: float = Field(..., gt=0)
    reference_price: Optional[float] = None
    expected_edge_pct: Optional[float] = None
    estimated_cost_pct: Optional[float] = None
    net_edge_pct: Optional[float] = None
    confidence_score: Optional[float] = Field(default=None, ge=0, le=1)
    reason: Optional[str] = None
    data_quality: DataQuality = DataQuality.DEMO
    quote_timestamp: Optional[datetime] = None
    bid_price: Optional[float] = None
    ask_price: Optional[float] = None
    spread_pct: Optional[float] = None
    volume: Optional[int] = None
    relative_volume: Optional[float] = None
    volatility: Optional[float] = None
    status: SignalStatus = SignalStatus.PENDING
    rejection_reason: Optional[str] = None


class SignalResponse(BaseModel):
    """Schema for signal API response."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    instrument_id: int
    trading_symbol: str
    strategy: str
    signal_type: str
    entry_price: float
    reference_price: Optional[float] = None
    expected_edge_pct: Optional[float] = None
    estimated_cost_pct: Optional[float] = None
    net_edge_pct: Optional[float] = None
    confidence_score: Optional[float] = None
    reason: Optional[str] = None
    data_quality: str
    quote_timestamp: Optional[datetime] = None
    bid_price: Optional[float] = None
    ask_price: Optional[float] = None
    spread_pct: Optional[float] = None
    volume: Optional[int] = None
    relative_volume: Optional[float] = None
    volatility: Optional[float] = None
    status: str
    rejection_reason: Optional[str] = None
    created_at: datetime
